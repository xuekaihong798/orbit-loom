export const PALETTE_MAP: Record<string, Palette> = Object.fromEntries(
  PALETTES.map((palette) => [palette.id, palette]),
);

export function paletteById(id: string): Palette {
  return PALETTE_MAP[id] ?? PALETTES[0];
}

export function rgb([r, g, b]: RGB): string {
  return `rgb(${r} ${g} ${b})`;
}

export function rgba([r, g, b]: RGB, alpha: number): string {
  return `rgba(${r},${g},${b},${alpha})`;
}

export function mix(a: RGB, b: RGB, t: number): RGB {
  return [
    a[0] + (b[0] - a[0]) * t,
    a[1] + (b[1] - a[1]) * t,
    a[2] + (b[2] - a[2]) * t,
  ];
}

export function swatchCss(palette: Palette): string {
  return `linear-gradient(100deg, ${rgb(palette.planets[3].trail)}, ${rgb(palette.sunMid)}, ${rgb(palette.planets[1].trail)})`;
}
